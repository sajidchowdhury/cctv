/**
 * Find the best-matching help content for a pathname.
 * Uses longest-prefix match (e.g. /products/new matches before /products).
 */
export function findHelp(pathname: string): HelpContent {
  // Try exact match first.
  if (HELP_CONTENT[pathname]) return HELP_CONTENT[pathname];

  // Try prefix matches, longest first.
  const sortedKeys = Object.keys(HELP_CONTENT).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (pathname === key || pathname.startsWith(key + "/") || pathname.startsWith(key)) {
      return HELP_CONTENT[key];
    }
  }

  return DEFAULT_HELP;
}
